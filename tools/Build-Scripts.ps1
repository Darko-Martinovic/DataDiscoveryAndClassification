<#
.SYNOPSIS
    Writes the generated scripts: the database project's seed (PostDeploy/Seed.sql) from the
    policy file, and install/Install.sql from the project's files.
.DESCRIPTION
    Run it after changing anything in DataDiscoveryAndClassification/ or policy/. CI runs it too
    and fails when the committed scripts differ from what it writes.
#>
[CmdletBinding()]
param(
    [string] $Policy = 'policy/sql_information_protection_default.json'
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$project = Join-Path $root 'DataDiscoveryAndClassification'
$utf8 = [System.Text.UTF8Encoding]::new($false)

function Write-Script([string] $path, [string[]] $lines) {
    New-Item -ItemType Directory -Force (Split-Path $path) | Out-Null
    [System.IO.File]::WriteAllText($path, (($lines -join "`n").TrimEnd() + "`n"), $utf8)
}

# Non-ASCII characters only occur inside JSON strings, so \uXXXX escapes keep the policy the same
# and the scripts plain ASCII, which every client reads alike whatever its code page.
$json = [System.IO.File]::ReadAllText((Join-Path $root $Policy), $utf8).Trim()
$json = [regex]::Replace($json, '[^\x00-\x7F]', { param($m) '\u{0:x4}' -f [int][char]$m.Value })
$json = $json -replace "`r`n", "`n" -replace "'", "''"

$seedPath = Join-Path $project 'PostDeploy/Seed.sql'
Write-Script $seedPath @(
    "-- Generated by tools/Build-Scripts.ps1 from $Policy. Don't edit it by hand."
    '-- Loads the policy into the DC tables the first time; later deployments keep your changes.'
    'IF NOT EXISTS (SELECT 1 FROM DC.SensitiveName)'
    "    EXECUTE DC.ImportPolicy @Policy = N'$json';"
)

# In dependency order.
$files = @(
    'Schema/DC.sql'
    'Tables/SensitiveName.sql'
    'Tables/InformationType.sql'
    'Tables/KeyWords.sql'
    'Functions/AddClassificationStatement.sql'
    'Views/GetMatchingColumns.sql'
    'Views/GetClassifiedColumns.sql'
    'Views/GetIntermediateResults.sql'
    'Views/GetLegacyClassifiedColumns.sql'
    'Procedures/ImportPolicy.sql'
    'Procedures/AcceptSuggestions.sql'
    'Procedures/RemoveClassification.sql'
    'Procedures/MigrateLegacyClassification.sql'
    'PostDeploy/Seed.sql'
)

$listed = $files | ForEach-Object { $_ -replace '/', [IO.Path]::DirectorySeparatorChar }
$missing = Get-ChildItem $project -Recurse -Filter *.sql |
    ForEach-Object { [IO.Path]::GetRelativePath($project, $_.FullName) } |
    Where-Object { $_ -notmatch '^(bin|obj)[\\/]' } |
    Where-Object { $_ -notin $listed }
if ($missing) {
    throw "Add these files to the list in tools/Build-Scripts.ps1: $($missing -join ', ')"
}

$install = @(
    "-- Generated by tools/Build-Scripts.ps1 from DataDiscoveryAndClassification/. Don't edit it by hand."
    '-- Installs the DC schema into the current database. Run it with sqlcmd or in SSMS.'
    'SET NOCOUNT ON;'
    'GO'
    'IF OBJECT_ID(N''sys.sensitivity_classifications'') IS NULL'
    'BEGIN'
    '    RAISERROR(N''DataDiscoveryAndClassification needs SQL Server 2019 or later, or Azure SQL.'', 16, 1);'
    '    SET NOEXEC ON;'
    'END'
    'ELSE IF (SELECT compatibility_level FROM sys.databases WHERE database_id = DB_ID()) < 130'
    'BEGIN'
    '    RAISERROR(N''DataDiscoveryAndClassification needs database compatibility level 130 or higher (it reads JSON).'', 16, 1);'
    '    SET NOEXEC ON;'
    'END'
    'ELSE IF SCHEMA_ID(N''DC'') IS NOT NULL'
    'BEGIN'
    '    RAISERROR(N''The DC schema exists already. Run install/Uninstall.sql first.'', 16, 1);'
    '    SET NOEXEC ON;'
    'END'
    'GO'
)
foreach ($file in $files) {
    $text = [System.IO.File]::ReadAllText((Join-Path $project $file), $utf8).Trim() -replace "`r`n", "`n"
    $install += ''
    $install += "-- $file"
    $install += $text
    $install += 'GO'
}
$install += ''
$install += 'SET NOEXEC OFF;'
$install += 'GO'

$installPath = Join-Path $root 'install/Install.sql'
Write-Script $installPath $install

Write-Host "Wrote $seedPath and $installPath"
